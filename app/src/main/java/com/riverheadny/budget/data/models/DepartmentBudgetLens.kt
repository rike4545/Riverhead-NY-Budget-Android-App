package com.riverheadny.budget.data.models

/**
 * The 2026 adopted budget by function, matched to the payroll summary where the match is clean.
 * Ported from iOS DepartmentBudgetLensData.swift.
 *
 * A null positions or salaryBase is a real answer: the payroll summary does not separate that
 * function cleanly, which is itself worth knowing — it is why some functions cannot be read as
 * "budget per employee" at all.
 */

enum class DepartmentBudgetCategory(val label: String) {
    GOVERNANCE("Governance"),
    PUBLIC_SAFETY("Public Safety"),
    SERVICES("Resident Services"),
    INFRASTRUCTURE("Infrastructure"),
    UTILITIES("Utilities"),
}

data class DepartmentBudgetRecord(
    val budgetDepartment: String,
    val staffDepartment: String?,
    val category: DepartmentBudgetCategory,
    val fundCode: String,
    val positions: Int?,
    val salaryBase: Double?,
    val adoptedTotal: Double,
    val keyTitles: List<String> = emptyList(),
    val note: String? = null,
) {
    val id: String get() = "$fundCode-$budgetDepartment"

    val otherExpense: Double? get() = salaryBase?.let { adoptedTotal - it }

    /** Share of the function that is base payroll. Above 1.0 means the crosswalk is imperfect. */
    val personnelShare: Double? get() =
        if (salaryBase != null && adoptedTotal > 0) salaryBase / adoptedTotal else null
}

